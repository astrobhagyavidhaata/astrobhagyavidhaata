async function askGemini({
  question,
  chartContext = {},
  conversationHistory = []
}) {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey) {
    throw new Error("GEMINI_API_KEY server environment में सेट नहीं है।");
  }

  if (!question || typeof question !== "string") {
    throw new Error("ग्राहक का प्रश्न आवश्यक है।");
  }

  const detailedPrediction = /विस्तार|विस्तृत|फलादेश|भविष्यवाणी|कब होगा|कब होगी|समय.?निर्धारण|कारण सहित|पूरा विश्लेषण|ट्रिपल|सिंक्रोन/i.test(question);
  const history = conversationHistory
    .slice(-12)
    .map((item) => ({
      role: item.role === "assistant" ? "model" : "user",
      parts: [{ text: String(item.text || item.content || "") }]
    }))
    .filter((item) => item.parts[0].text.trim());

  const chartText = JSON.stringify(chartContext, null, 2);
  const requestText =
    "उपलब्ध कुंडली का संदर्भ:\n" +
    chartText +
    "\n\nग्राहक का वर्तमान प्रश्न:\n" +
    question +
    (detailedPrediction
      ? "\n\nयह विस्तृत फलादेश का अनुरोध है। सिस्टम निर्देशों में दिया 7-खंड वाला प्रारूप अपनाएं। पर्याप्त डेटा न हो तो कमी बताएं; कोई तथ्य न गढ़ें।"
      : "");

  const contents = [
    ...history,
    { role: "user", parts: [{ text: requestText }] }
  ];

  const url =
    `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent`;

  const response = await fetch(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "x-goog-api-key": apiKey
    },
    body: JSON.stringify({
      system_instruction: {
        parts: [{ text: SYSTEM_INSTRUCTION }]
      },
      contents,
      generationConfig: {
        temperature: 0.4,
        maxOutputTokens: detailedPrediction ? 1800 : 450
      }
    }),
    signal: AbortSignal.timeout(25000)
  });

  const data = await response.json();

  if (!response.ok) {
    throw new Error(
      data.error?.message || "Gemini API से उत्तर प्राप्त नहीं हुआ।"
    );
  }

  const answer = data.candidates?.[0]?.content?.parts
    ?.map((part) => part.text || "")
    .join("")
    .trim();

  if (!answer) {
    throw new Error("Gemini ने कोई उत्तर नहीं दिया।");
  }

  return answer;
}

module.exports = { askGemini };
